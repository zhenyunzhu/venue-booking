-- 3. 按模板生成"明天"的场次（库存=场馆场地数）
-- ---------------------------------------------------------------------
INSERT INTO t_venue_slot (venue_id, slot_date, start_time, end_time, price,
                          total_stock, remain_stock, status)
SELECT v.id,
       DATE_ADD(CURDATE(), INTERVAL 1 DAY),
       t.start_time,
       t.end_time,
       t.price,
       v.court_count,
       v.court_count,
       1
FROM t_venue v
         JOIN t_slot_template t ON t.venue_id = v.id AND t.status = 1 AND t.deleted = 0
WHERE v.deleted = 0;

